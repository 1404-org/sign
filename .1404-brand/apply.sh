#!/usr/bin/env bash
# Copy generated brand assets into the Documenso tree, then apply text/colour changes.
set -euo pipefail
cd "$(dirname "$0")/.."
B=.1404-brand/out
[ -f $B/logo.png ] || (cd .1404-brand && python3 make_assets.py)
for dir in apps/remix/public packages/assets; do
  cp $B/favicon.ico $dir/favicon.ico; cp $B/icon-16.png $dir/favicon-16x16.png; cp $B/icon-32.png $dir/favicon-32x32.png
  cp $B/apple-touch-icon.png $dir/apple-touch-icon.png; cp $B/opengraph-image.jpg $dir/opengraph-image.jpg
done
for f in apps/remix/public/static/logo.png packages/assets/static/logo.png packages/assets/logo.png packages/email/static/logo.png; do cp $B/logo.png $f; done
cp $B/logo_icon.png packages/assets/logo_icon.png
python3 -c "
from PIL import Image
for p in ['apps/remix/public/static/og-share-frame2.png','packages/assets/static/og-share-frame2.png','packages/assets/static/og-share-frame.png']:
    Image.open('.1404-brand/out/opengraph-image.jpg').save(p)"
D=$(cat $B/wordmark.path); VB=$(cat $B/wordmark.viewbox); IFS='|' read S TX TY SC < $B/icon.inner || true
python3 - "$D" "$VB" "$S" "$TX" "$TY" "$SC" <<'PY'
import sys; D,VB,S,TX,TY,SC=sys.argv[1:]
open('apps/remix/app/components/general/branding-logo.tsx','w').write(f"""import type {{ SVGAttributes }} from 'react';

export type LogoProps = SVGAttributes<SVGSVGElement>;

// 1404 wordmark (Instrument Serif), generated by .1404-brand/make_assets.py.
export const BrandingLogo = ({{ ...props }}: LogoProps) => {{
  return (
    <svg xmlns="http://www.w3.org/2000/svg" viewBox="{VB}" {{...props}}>
      <path
        fill="currentColor"
        d="{D}"
      />
    </svg>
  );
}};
""")
open('apps/remix/app/components/general/branding-logo-icon.tsx','w').write(f"""import type {{ SVGAttributes }} from 'react';

export type LogoProps = SVGAttributes<SVGSVGElement>;

// 1404 wordmark centred in a square, generated by .1404-brand/make_assets.py.
export const BrandingLogoIcon = ({{ ...props }}: LogoProps) => {{
  return (
    <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {S} {S}" {{...props}}>
      <path
        transform="translate({TX} {TY}) scale({SC})"
        fill="currentColor"
        d="{D}"
      />
    </svg>
  );
}};
""")
PY
python3 .1404-brand/rebrand.py
